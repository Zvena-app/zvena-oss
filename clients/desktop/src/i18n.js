const DICTS = { en, zh, hi, es, ar, fr, bn, pt, ru, id };

/** One of the ten interface languages for a system locale ("pt-BR" → "pt", "in" → "id"). */
function localeOf(systemLocale) {
  const base = String(systemLocale || "en").toLowerCase().split(/[-_]/)[0];
  if (base === "in") return "id";
  return LOCALES.includes(base) ? base : "en";
}

/** A translator for the locale: t(key, { word }) with English for anything missing. */
function translator(locale) {
  const dict = DICTS[locale] || en;
  return (key, vars) => {
    const s = dict[key] ?? en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

const isRtl = (locale) => locale === "ar";

module.exports = { LOCALES, DICTS, localeOf, translator, isRtl };
