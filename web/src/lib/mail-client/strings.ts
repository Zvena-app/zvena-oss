/** A string of Mail; `{name}` placeholders are filled from `vars`. English and Russian are here, the rest in src/i18n/catalogs/mail/. */
export function mailText(locale: string, key: MailKey, vars?: Record<string, string | number>): string {
  const s = locale === "ru" ? ru[key] : ((locale === "en" ? undefined : msg("mail", locale, key)) ?? en[key]);
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
