const DICTS: Partial<Record<Locale, Record<MessageKey, string>>> = { ru, en };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = DICTS[locale]?.[key] ?? msg("web", locale, key) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function isLocale(v: unknown): v is Locale {
  return isKnownLocale(v);
}

/**
 * The interface language: the person's explicit choice (the language picker,
 * kept in the zv_lang cookie), otherwise English. The browser's languages are
 * not used to switch away from English; `languageHint` says which one the
 * picker could suggest.
 */
export function resolveLocale(pref: string | null | undefined, _languages: readonly string[] = []): Locale {
  return isLocale(pref) ? pref : "en";
}

/** The first of the browser's languages zvena speaks (for a "Switch to …?" hint), if not English. */
export function languageHint(languages: readonly string[]): Locale | null {
  for (const tag of languages) {
    const l = localeOfTag(tag);
    if (l) return l === "en" ? null : l;
  }
  return null;
}

export function parseAcceptLanguage(header: string | null | undefined): string[] {
  if (!header) return [];
  return header
    .split(",")
    .map((part) => {
      const [tag, q] = part.trim().split(";q=");
      return { tag: tag.trim(), q: q ? Number(q) : 1 };
    })
    .filter((x) => x.tag && Number.isFinite(x.q))
    .sort((a, b) => b.q - a.q)
    .map((x) => x.tag);
}

/** Human-readable bytes in the interface's language ("2 GB", «2 ГБ», "2 Go"…). */
export function formatBytes(n: number, locale: Locale): string {
  let v = n;
  let i = 0;
  while (v >= 1024 && i < 4) {
    v /= 1024;
    i++;
  }
  if (locale === "en" || locale === "ru") {
    const units = locale === "ru" ? ["Б", "КБ", "МБ", "ГБ", "ТБ"] : ["B", "KB", "MB", "GB", "TB"];
    const num = i === 0 ? String(Math.round(v)) : v.toFixed(v < 10 ? 1 : 0).replace(/\.0$/, "");
    return `${locale === "ru" ? num.replace(".", ",") : num} ${units[i]}`;
  }
  const unit = (["byte", "kilobyte", "megabyte", "gigabyte", "terabyte"] as const)[i];
  return new Intl.NumberFormat(intlTag(locale), { style: "unit", unit, unitDisplay: "short", maximumFractionDigits: i === 0 || v >= 10 ? 0 : 1 }).format(v);
}
