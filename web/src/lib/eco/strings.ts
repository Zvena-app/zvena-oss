/** English and Russian are here; the other languages come from src/i18n/catalogs/eco/. */
export function ecoText(locale: string, key: EcoKey, vars?: Record<string, string | number>): string {
  const text = ecoWord(locale, key);
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}

function ecoWord(locale: string, key: EcoKey): string {
  if (locale === "ru") return ru[key];
  return (locale === "en" ? undefined : msg("eco", locale, key)) ?? en[key];
}
