/** English and Russian are here; the other languages come from src/i18n/catalogs/calendar/. */
export function calText(locale: string, key: CalKey, vars?: Record<string, string | number>): string {
  const s = locale === "ru" ? ru[key] : ((locale === "en" ? undefined : msg("calendar", locale, key)) ?? en[key]);
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
