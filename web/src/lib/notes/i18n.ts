const DICTS = { en, ru } as const;

export type NotesT = (key: NotesKey, vars?: Record<string, string | number>) => string;

/** English and Russian are here; the other languages come from src/i18n/catalogs/docs/. */
export function notesT(locale: string, key: NotesKey, vars?: Record<string, string | number>): string {
  const dict = (locale === "ru" ? DICTS.ru : DICTS.en) as Record<NotesKey, string>;
  let s = (locale === "ru" || locale === "en" ? dict[key] : msg("docs", locale, key)) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useNotesT(): { t: NotesT; locale: Locale } {
  const { locale } = useI18n();
  const t = useCallback<NotesT>((key, vars) => notesT(locale, key, vars), [locale]);
  return { t, locale };
}

/** "5m ago", "Yesterday", or a date — Notion's relative "Edited …". */
export function relativeTime(t: NotesT, locale: string, at: number, now = Date.now()): string {
  const s = Math.max(0, Math.round((now - at) / 1000));
  if (s < 60) return t("time.justNow");
  const m = Math.round(s / 60);
  if (m < 60) return t("time.minutes", { n: m });
  const h = Math.round(m / 60);
  if (h < 24) return t("time.hours", { n: h });
  const d = Math.round(h / 24);
  if (d === 1) return t("time.yesterday");
  if (d < 7) return t("time.days", { n: d });
  return new Date(at).toLocaleDateString(intlOf(locale), { month: "short", day: "numeric", year: new Date(at).getFullYear() === new Date(now).getFullYear() ? undefined : "numeric" });
}
