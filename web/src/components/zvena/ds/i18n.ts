export type DsKey = keyof typeof en;

/** A string of the shared components; `{name}` placeholders are filled from `vars`. English and Russian are here, the rest in src/i18n/catalogs/ds/. */
export function dt(locale: string, key: DsKey, vars?: Record<string, string | number>): string {
  const s = locale === "ru" ? ru[key] : ((locale === "en" ? undefined : msg("ds", locale, key)) ?? en[key]);
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
