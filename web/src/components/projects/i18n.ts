export type PKey = keyof typeof M;

/** Russian and English are here; the other languages come from src/i18n/catalogs/projects/. */
export function pt(locale: string, key: PKey, vars?: Record<string, string | number>): string {
  let s: string = locale === "ru" ? M[key][0] : locale === "en" ? M[key][1] : (msg("projects", locale, key) ?? M[key][1]);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export type PT = (key: PKey, vars?: Record<string, string | number>) => string;

export function useT(): { t: PT; locale: "ru" | "en"; lang: Locale } {
  const { locale } = useI18n();
  const t = useCallback<PT>((key, vars) => pt(locale, key, vars), [locale]);
  // `locale` picks en/ru-only data (sample content); `lang` is the interface language, for dates.
  return { t, locale: enRu(locale), lang: locale };
}
